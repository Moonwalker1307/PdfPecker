// Regenerates src/PdfPecker/Text/SaslPrep.g.cs: the stringprep tables (RFC 3454, appendices A to D) that SASLprep
// (RFC 4013) uses to prepare AES-256 passwords, as ISO 32000-2 section 7.6.4.3.3 asks.
//
// Usage (from the repository root, .NET 10 SDK):
//   dotnet run tools/StringPrep/build.cs -- <rfc3454.txt> [out]
//
// The input is the RFC's text, https://www.rfc-editor.org/rfc/rfc3454.txt (see THIRD-PARTY-NOTICES.md). The RFC never
// changes, so its SHA-256 is checked to catch a damaged or different file. The tables are Unicode 3.2's, which
// stringprep fixes for good.
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

const string ExpectedSha256 = "eb722fa698fb7e8823b835d9fd263e4cdb8f1c7b0d234edf7f0e3bd2ccbb2c79";

if (args.Length < 1)
{
    Console.Error.WriteLine("Usage: dotnet run tools/StringPrep/build.cs -- <rfc3454.txt> [out]");
    return 1;
}
var bytes = File.ReadAllBytes(args[0]);
string hash = Convert.ToHexStringLower(SHA256.HashData(bytes));
if (hash != ExpectedSha256) throw new InvalidDataException($"{args[0]} has SHA-256 {hash}, not that of RFC 3454 ({ExpectedSha256}).");
string output = args.Length > 1 ? args[1] : Path.Combine("src", "PdfPecker", "Text", "SaslPrep.g.cs");
var lines = Encoding.ASCII.GetString(bytes).Split('\n');

// A table's entries are lines such as "   0221", "   0234-024F" or "   00AD; ; Map to nothing" between its start and
// end markers; the page footers and headers in between match no entry.
var entry = new Regex(@"^   ([0-9A-F]{4,6})(?:-([0-9A-F]{4,6}))?(?:;.*)?\r?$");
List<(int First, int Last)> Table(string name)
{
    int start = Array.FindIndex(lines, l => l.TrimEnd() == $"   ----- Start Table {name} -----");
    int end = Array.FindIndex(lines, l => l.TrimEnd() == $"   ----- End Table {name} -----");
    if (start < 0 || end < start) throw new InvalidDataException("No table " + name);
    var ranges = new List<(int, int)>();
    for (int i = start + 1; i < end; i++)
    {
        var m = entry.Match(lines[i]);
        if (!m.Success) continue;
        int first = Hex(m.Groups[1].Value), last = m.Groups[2].Success ? Hex(m.Groups[2].Value) : first;
        ranges.Add((first, last));
    }
    return ranges;
}

// B.1 maps only to nothing; its entries have an empty mapping field.
var mappedToNothing = Merge(Table("B.1"));
var spaces = Merge(Table("C.1.2"));
var prohibited = Merge(new[] { "C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9" }.SelectMany(Table));
var unassigned = Merge(Table("A.1"));
var randAL = Merge(Table("D.1"));
var l = Merge(Table("D.2"));

var o = new StringBuilder();
o.Append("""
    // <auto-generated>
    // Generated by tools/StringPrep/build.cs from the tables of RFC 3454 (stringprep), which are Unicode 3.2's.
    // Do not edit by hand.
    // </auto-generated>
    namespace PdfPecker.Text;

    internal static partial class SaslPrep
    {
        // Each table is a list of code point ranges, first and last, sorted and apart.

        // B.1: commonly mapped to nothing.

    """.ReplaceLineEndings("\n"));
Ranges("MappedToNothing", mappedToNothing);
o.Append("\n    // C.1.2: non-ASCII spaces, which SASLprep maps to U+0020.\n");
Ranges("NonAsciiSpaces", spaces);
o.Append("\n    // C.1.2 to C.9: what SASLprep prohibits in its output.\n");
Ranges("ProhibitedRanges", prohibited);
o.Append("\n    // A.1: unassigned in Unicode 3.2.\n");
Ranges("UnassignedRanges", unassigned);
o.Append("\n    // D.1: bidirectional category R or AL.\n");
Ranges("RandALCatRanges", randAL);
o.Append("\n    // D.2: bidirectional category L.\n");
Ranges("LCatRanges", l);
o.Append("}\n");
File.WriteAllText(output, o.ToString(), new UTF8Encoding(false));
Console.WriteLine($"{mappedToNothing.Count} mapped to nothing, {spaces.Count} spaces, {prohibited.Count} prohibited, "
    + $"{unassigned.Count} unassigned, {randAL.Count} RandALCat and {l.Count} LCat ranges");
return 0;

static int Hex(string s) => int.Parse(s, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

// Sorts the ranges and joins the ones that overlap or touch.
static List<(int First, int Last)> Merge(IEnumerable<(int First, int Last)> ranges)
{
    var merged = new List<(int First, int Last)>();
    foreach (var (first, last) in ranges.OrderBy(r => r.First))
    {
        if (last < first) throw new InvalidDataException($"Range {first:X4}-{last:X4} is backwards");
        if (merged.Count > 0 && first <= merged[^1].Last + 1) merged[^1] = (merged[^1].First, Math.Max(merged[^1].Last, last));
        else merged.Add((first, last));
    }
    return merged;
}

void Ranges(string name, List<(int First, int Last)> ranges)
{
    o.Append($"    internal static ReadOnlySpan<int> {name} => [\n");
    foreach (var chunk in ranges.Chunk(8))
        o.Append("        ").AppendJoin(", ", chunk.Select(r => $"0x{r.First:X}, 0x{r.Last:X}")).Append(",\n");
    o.Append("    ];\n");
}
