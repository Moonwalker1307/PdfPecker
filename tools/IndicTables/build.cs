// Regenerates src/PdfPecker/Fonts/IndicTables.g.cs: the Indic syllabic categories and positions that HarfBuzz's Indic
// shaper gives each character, and the canonical decompositions of the Indic letters and vowel signs.
//
// Usage (from the repository root, .NET 10 SDK):
//   dotnet run tools/IndicTables/build.cs -- <hb-ot-shaper-indic-table.cc> [out]
//
// The input is HarfBuzz's generated table, for example
// https://raw.githubusercontent.com/harfbuzz/harfbuzz/14.6.0/src/hb-ot-shaper-indic-table.cc (HarfBuzz's "Old MIT"
// licence, see THIRD-PARTY-NOTICES.md). Its packed lookup is evaluated for every code point of the ranges below, so the
// categories are exactly HarfBuzz's, overrides included. The decompositions come from .NET's own normalization, which
// is fine because canonical decompositions never change once a character is encoded. Each is one step deep, as
// Unicode lists them.
using System.Text;
using System.Text.RegularExpressions;

const string HarfBuzzVersion = "14.6.0";

// The characters the Indic shaper gives a category: the placeholders and superscripts of Latin-1, the nine Indic
// blocks, Vedic Extensions, the joiners, dashes and subscripts, the dotted circle and squares, Devanagari Extended and
// the Grantha marks Tamil borrows. HarfBuzz's table also covers Khmer and Myanmar, which other shapers handle.
(int First, int Last)[] ranges =
[
    (0x0020, 0x00DF), (0x0900, 0x0D7F), (0x1CD0, 0x1CFF), (0x200C, 0x2087), (0x25CC, 0x25FF), (0xA8E0, 0xA8FF),
    (0x11300, 0x1133F),
];

string source = File.ReadAllText(args[0]);
string output = args.Length > 1 ? args[1] : Path.Combine("src", "PdfPecker", "Fonts", "IndicTables.g.cs");

var categoryNames = new Dictionary<string, int>
{
    ["X"] = 0, ["C"] = 1, ["V"] = 2, ["N"] = 3, ["H"] = 4, ["ZWNJ"] = 5, ["ZWJ"] = 6, ["M"] = 7, ["SM"] = 8, ["A"] = 9,
    ["GB"] = 10, ["DC"] = 11, ["RS"] = 12, ["MP"] = 13, ["Rf"] = 14, ["R"] = 15, ["CM"] = 16, ["S"] = 17, ["CS"] = 18,
    ["SP"] = 57,
};
var positionNames = new Dictionary<string, int>
{
    ["L"] = 3, ["LM"] = 2, ["C"] = 4, ["A"] = 5, ["T"] = 6, ["BS"] = 7, ["B"] = 8, ["AS"] = 9, ["R"] = 11,
    ["AP"] = 12, ["SM"] = 13, ["X"] = 14,
};

var values = Regex.Matches(Block("_hb_indic_values"), @"_\((\w+),(\w+)\)")
    .Select(m => categoryNames.TryGetValue(m.Groups[1].Value, out int cat)
        ? (ushort)(cat | positionNames[m.Groups[2].Value] << 8)
        : (ushort)(14 << 8)) // a Khmer or Myanmar category: not one of the Indic shaper's
    .ToArray();
var u8 = Regex.Matches(Block("_hb_indic_u8"), @"\d+").Select(m => int.Parse(m.Value)).ToArray();
var lookup = Regex.Match(source, @"return u<(\d+)u \? \(uint8_t\)\((.*?)\) : (\d+);").Groups;
int limit = int.Parse(lookup[1].Value), outside = int.Parse(lookup[3].Value);
if (!lookup[2].Value.StartsWith("_hb_indic_u8[996u+_hb_indic_u8[488u+((_hb_indic_u8[186u+((_hb_indic_u8[70u+"))
    throw new InvalidOperationException("The packed table's lookup changed; update Index below to match it.");

var o = new StringBuilder();
o.Append($$"""
    // <auto-generated>
    // Generated by tools/IndicTables from HarfBuzz {{HarfBuzzVersion}}'s hb-ot-shaper-indic-table.cc. Do not edit by hand.
    // </auto-generated>
    namespace PdfPecker.Fonts;

    internal static partial class IndicTables
    {
        internal const string HarfBuzzVersion = "{{HarfBuzzVersion}}";

    """);
foreach (var (first, last) in ranges)
{
    o.Append($"\n    // U+{first:X4} to U+{last:X4}: the category in the low byte, the position in the high byte.\n");
    o.Append($"    private static ReadOnlySpan<ushort> Range{first:X4} => [");
    for (int cp = first; cp <= last; cp++)
    {
        if ((cp - first) % 12 == 0) o.Append("\n        ");
        o.Append($"0x{values[Index(cp)]:X4}, ");
    }
    o.Append("\n    ];\n");
}
o.Append("\n    /// <summary>The category (low byte) and position (high byte) of a character.</summary>\n");
o.Append("    public static ushort Get(int cp) => cp switch\n    {\n");
foreach (var (first, last) in ranges)
    o.Append($"        >= 0x{first:X4} and <= 0x{last:X4} => Range{first:X4}[cp - 0x{first:X4}],\n");
o.Append($"        _ => 0x{values[outside]:X4},\n    }};\n");

o.Append("\n    // Canonical decompositions in the Indic blocks: code point, first, second.\n");
o.Append("    internal static ReadOnlySpan<int> Decompositions => [");
int count = 0;
for (int cp = 0x0900; cp <= 0x0D7F; cp++)
{
    string s = char.ConvertFromUtf32(cp), d = s.Normalize(NormalizationForm.FormD);
    if (d == s) continue;
    // A three-part vowel sign decomposes in two steps: into the two-part sign and the last part.
    string first = d[..^1].Normalize(NormalizationForm.FormC);
    if (first.Length != 1) throw new InvalidOperationException($"U+{cp:X4} decomposes into {first} and a last part.");
    if (count++ % 4 == 0) o.Append("\n        ");
    o.Append($"0x{cp:X4}, 0x{(int)first[0]:X4}, 0x{(int)d[^1]:X4}, ");
}
o.Append("\n    ];\n}\n");
File.WriteAllText(output, o.ToString().Replace(", \n", ",\n"));
Console.WriteLine($"{output}: {ranges.Sum(r => r.Last - r.First + 1)} characters, {count} decompositions");
return 0;

// The values of the packed table (packtab: [2^4,2^3,2^3,2^2,2^1]) for a code point, as _hb_indic_get_categories_index.
int Index(int u)
{
    if (u >= limit) return outside;
    int b4 = (u8[u >> 10] >> ((u >> 9 & 1) << 2)) & 15;
    return u8[996 + u8[488 + ((u8[186 + ((u8[70 + (b4 << 3) + ((u >> 6) & 7)]) << 3) + ((u >> 3) & 7)]) << 2) + ((u >> 1) & 3)] + (u & 1)];
}

string Block(string name) => Regex.Match(source, name + @"\[\d+\]\s*=\s*\{(.*?)\};", RegexOptions.Singleline).Groups[1].Value;
