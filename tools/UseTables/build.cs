// Regenerates src/PdfPecker/Fonts/UseTables.g.cs: the categories that HarfBuzz's Universal Shaping Engine gives the
// characters of the scripts PdfPecker shapes with it (Sinhala and Tibetan), and of the common characters that can be in
// their runs.
//
// Usage (from the repository root, .NET 10 SDK):
//   dotnet run tools/UseTables/build.cs -- <hb-ot-shaper-use-table.hh> <hb-ot-shaper-use-machine.rl> [out]
//
// The inputs are HarfBuzz's generated table and its syllable machine, for example
// https://raw.githubusercontent.com/harfbuzz/harfbuzz/14.6.0/src/hb-ot-shaper-use-table.hh and
// https://raw.githubusercontent.com/harfbuzz/harfbuzz/14.6.0/src/hb-ot-shaper-use-machine.rl (HarfBuzz's "Old MIT"
// licence, see THIRD-PARTY-NOTICES.md). The machine gives the values of the category names; the table's packed lookup
// is evaluated for every code point of the ranges below, so the categories are exactly HarfBuzz's, overrides included.
using System.Text;
using System.Text.RegularExpressions;

const string HarfBuzzVersion = "14.6.0";

// Latin-1 (digits, hyphen, brackets, no-break space), the grapheme joiner, Sinhala, Tibetan, the joiners, dashes and
// superscripts, the dotted circle, the variation selectors and the Sinhala archaic numbers.
(int First, int Last)[] ranges =
[
    (0x0020, 0x00DF), (0x034F, 0x034F), (0x0D80, 0x0DFF), (0x0F00, 0x0FFF), (0x2000, 0x2087), (0x25CC, 0x25CC),
    (0xFE00, 0xFE0F), (0x111E0, 0x111FF),
];

// The table is written twice, for speed and for size; the first is the one HarfBuzz builds by default.
string source = File.ReadAllText(args[0]).Split("#else")[0];
string output = args.Length > 2 ? args[2] : Path.Combine("src", "PdfPecker", "Fonts", "UseTables.g.cs");
var names = Regex.Matches(File.ReadAllText(args[1]), @"export (\w+)\s*=\s*(\d+);")
    .ToDictionary(m => m.Groups[1].Value, m => int.Parse(m.Groups[2].Value));

var u8 = Array("hb_use_u8");
var u16 = Array("hb_use_u16");
const string Lookup = "return u<921600u ? (uint8_t)(hb_use_u8[2969u+((hb_use_u8[625u+hb_use_u16[((hb_use_u8[113u+((hb_use_b4(hb_use_u8,((((((((u)>>1))>>3))>>3))>>5)))<<5)+((((((((u)>>1))>>3))>>3))&31)])<<3)+((((((u)>>1))>>3))&7)]+((((u)>>1))&7)])<<1)+((u)&1)]) : O;";
if (!source.Contains(Lookup, StringComparison.Ordinal))
    throw new InvalidOperationException("The packed table's lookup changed; update Category below to match it.");

var o = new StringBuilder();
o.Append($$"""
    // <auto-generated>
    // Generated by tools/UseTables from HarfBuzz {{HarfBuzzVersion}}'s hb-ot-shaper-use-table.hh. Do not edit by hand.
    // </auto-generated>
    namespace PdfPecker.Fonts;

    internal static class UseTables
    {
        internal const string HarfBuzzVersion = "{{HarfBuzzVersion}}";

    """);
foreach (var (first, last) in ranges)
{
    if (first == last) continue;
    o.Append($"\n    // U+{first:X4} to U+{last:X4}.\n");
    o.Append($"    private static ReadOnlySpan<byte> Range{first:X4} => [");
    for (int cp = first; cp <= last; cp++)
    {
        if ((cp - first) % 16 == 0) o.Append("\n        ");
        o.Append($"{Category(cp)}, ");
    }
    o.Append("\n    ];\n");
}
o.Append("\n    /// <summary>The Universal Shaping Engine category of a character, as HarfBuzz's machine numbers them.</summary>\n");
o.Append("    public static byte Get(int cp) => cp switch\n    {\n");
foreach (var (first, last) in ranges)
    o.Append(first == last
        ? $"        0x{first:X4} => {Category(first)},\n"
        : $"        >= 0x{first:X4} and <= 0x{last:X4} => Range{first:X4}[cp - 0x{first:X4}],\n");
o.Append($"        _ => {names["O"]},\n    }};\n}}\n");
File.WriteAllText(output, o.ToString().Replace(", \n", ",\n"));
Console.WriteLine($"{output}: {ranges.Sum(r => r.Last - r.First + 1)} characters");
return 0;

// hb_use_get_category, packtab [2^4,2^5,2^3,2^3,2^1].
int Category(int u)
{
    if (u >= 921600) return names["O"];
    int b4 = (u8[u >> 13] >> ((u >> 12 & 1) << 2)) & 15;
    return u8[2969 + (u8[625 + u16[(u8[113 + (b4 << 5) + ((u >> 7) & 31)] << 3) + ((u >> 4) & 7)] + ((u >> 1) & 7)] << 1) + (u & 1)];
}

// An array of the table, whose entries are numbers or, in the last part, category names.
int[] Array(string name)
    => Regex.Matches(Regex.Match(source, name + @"\[\d+\]\s*=\s*\{(.*?)\};", RegexOptions.Singleline).Groups[1].Value, @"\w+")
        .Select(m => int.TryParse(m.Value, out int v) ? v : names[m.Value]).ToArray();
