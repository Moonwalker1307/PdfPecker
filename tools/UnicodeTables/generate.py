#!/usr/bin/env python3
"""Generates src/PdfPecker/Text/UnicodeTables.g.cs from the Unicode Character Database.

Usage: python3 generate.py <ucd-folder> <output.cs>

The folder needs DerivedBidiClass.txt, BidiMirroring.txt, BidiBrackets.txt, ArabicShaping.txt and UnicodeData.txt of one
Unicode version, for example from https://www.unicode.org/Public/16.0.0/ucd/ (DerivedBidiClass.txt is in extracted/).
"""
import os
import sys

UCD_VERSION = "16.0.0"
BIDI = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
        "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
# Joining types as the shaper uses them: C (join causing) behaves as D; Syriac Alaph and Dalath/Rish get their own.
JOINING = {"U": 0, "L": 1, "R": 2, "D": 3, "C": 3, "T": 4}
ALAPH, DALATH_RISH = 5, 6
FORMS = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}


def lines(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                yield [p.strip() for p in line.split(";")]


def code_range(s):
    if ".." in s:
        a, b = s.split("..")
        return int(a, 16), int(b, 16)
    return int(s, 16), int(s, 16)


def main(ucd, out):
    # Bidi classes, as run-length ranges over all code points (unlisted ones are L).
    classes = bytearray(0x110000)
    for f in lines(os.path.join(ucd, "DerivedBidiClass.txt")):
        lo, hi = code_range(f[0])
        v = BIDI.index(f[1])
        for cp in range(lo, hi + 1):
            classes[cp] = v
    starts, values = [], []
    for cp in range(0x110000):
        if cp == 0 or classes[cp] != classes[cp - 1]:
            starts.append(cp)
            values.append(classes[cp])

    mirrors = sorted((int(f[0], 16), int(f[1], 16)) for f in lines(os.path.join(ucd, "BidiMirroring.txt")))
    brackets = sorted((int(f[0], 16), int(f[1], 16), f[2]) for f in lines(os.path.join(ucd, "BidiBrackets.txt")))

    joining = {}
    for f in lines(os.path.join(ucd, "ArabicShaping.txt")):
        cp = int(f[0], 16)
        t = JOINING[f[2]]
        if f[3] == "ALAPH":
            t = ALAPH
        elif f[3] == "DALATH RISH":
            t = DALATH_RISH
        joining[cp] = t
    join_ranges = []
    for cp in sorted(joining):
        if join_ranges and join_ranges[-1][1] == cp - 1 and join_ranges[-1][2] == joining[cp]:
            join_ranges[-1][1] = cp
        else:
            join_ranges.append([cp, cp, joining[cp]])

    forms, lam_alef = [], []
    ccc = {}
    decomp = []
    for f in lines(os.path.join(ucd, "UnicodeData.txt")):
        cp = int(f[0], 16)
        if int(f[3]) != 0:
            ccc[cp] = int(f[3])
        if f[5] and not f[5].startswith("<") and (0x0590 <= cp <= 0x08FF or 0xFB1D <= cp <= 0xFB4F):
            d = [int(x, 16) for x in f[5].split()]
            decomp.append((cp, d[0], d[1] if len(d) > 1 else 0))
        parts = f[5].split()
        if not parts or parts[0] not in FORMS or not (0xFB50 <= cp <= 0xFEFF):
            continue
        chars = [int(p, 16) for p in parts[1:]]
        if len(chars) == 1:
            forms.append((chars[0] << 2 | FORMS[parts[0]], cp))
        elif len(chars) == 2 and chars[0] == 0x0644:
            lam_alef.append((chars[1] << 2 | FORMS[parts[0]], cp))
    forms.sort()
    lam_alef.sort()
    ccc_ranges = []
    for cp in sorted(ccc):
        if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == ccc[cp]:
            ccc_ranges[-1][1] = cp
        else:
            ccc_ranges.append([cp, cp, ccc[cp]])

    def ints(name, data, per_line=16, typ="int"):
        s = f"    internal static ReadOnlySpan<{typ}> {name} => [\n"
        for i in range(0, len(data), per_line):
            s += "        " + ", ".join(f"0x{v:X}" for v in data[i:i + per_line]) + ",\n"
        return s + "    ];\n"

    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write(f"""// <auto-generated>
// Generated by tools/UnicodeTables/generate.py from the Unicode Character Database {UCD_VERSION}
// (DerivedBidiClass, BidiMirroring, BidiBrackets, ArabicShaping, UnicodeData). Do not edit by hand.
// </auto-generated>
namespace PdfPecker.Text;

internal static partial class UnicodeTables
{{
    internal const string Version = "{UCD_VERSION}";

    // Bidi_Class (BidiClass values) of every code point: BidiClassValues[k] from BidiClassStarts[k] up to the next start.
""")
        o.write(ints("BidiClassStarts", starts))
        o.write(ints("BidiClassValues", values, 32, "byte"))
        o.write("\n    // Bidi_Mirroring_Glyph pairs: code point, mirrored code point, sorted by the first.\n")
        o.write(ints("MirrorPairs", [v for p in mirrors for v in p]))
        o.write("\n    // Bidi_Paired_Bracket: code point, its pair, 1 for an opening bracket and 0 for a closing one.\n")
        o.write(ints("BracketPairs", [v for b in brackets for v in (b[0], b[1], 1 if b[2] == "o" else 0)], 15))
        o.write("\n    // Joining_Type of the characters ArabicShaping lists: first, last, type (see JoiningType).\n")
        o.write(ints("JoiningRanges", [v for r in join_ranges for v in r], 15))
        o.write("\n    // Canonical_Combining_Class of the characters that have one: first, last, class.\n")
        o.write(ints("CombiningClassRanges", [v for r in ccc_ranges for v in r], 15))
        o.write("\n    // Canonical decompositions of Hebrew and Arabic letters: code point, first, second (0 for a singleton).\n")
        o.write(ints("Decompositions", [v for d in decomp for v in d], 15))
        o.write("\n    // Arabic presentation forms: (letter << 2 | form) and the presentation form, sorted; form 0 isolated,\n")
        o.write("    // 1 final, 2 initial, 3 medial.\n")
        o.write(ints("PresentationForms", [v for p in forms for v in p]))
        o.write("\n    // Lam-alef ligatures: (alef << 2 | form) and the ligature, for lam followed by that alef.\n")
        o.write(ints("LamAlefForms", [v for p in lam_alef for v in p]))
        o.write("}\n")
    print(f"{len(starts)} bidi ranges, {len(mirrors)} mirror pairs, {len(brackets)} brackets, "
          f"{len(join_ranges)} joining ranges, {len(ccc_ranges)} ccc ranges, {len(forms)} forms, {len(lam_alef)} lam-alef")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
