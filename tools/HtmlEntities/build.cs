// Regenerates src/PdfPecker/Html/HtmlEntities.g.cs: the named character references of the HTML Standard.
//
// Usage (from the repository root, .NET 10 SDK):
//   dotnet run tools/HtmlEntities/build.cs -- <entities.json> [out]
//
// The input is the WHATWG HTML Standard's https://html.spec.whatwg.org/entities.json (portions of the standard
// incorporated into source code are under the BSD 3-Clause License, see THIRD-PARTY-NOTICES.md). The list is closed:
// the standard says it will not change, so the counts below are checked to catch a damaged or different file.
using System.Text;
using System.Text.Json;

const int ExpectedNames = 2231, ExpectedLegacy = 106;

using var json = JsonDocument.Parse(File.ReadAllBytes(args[0]));
string output = args.Length > 1 ? args[1] : Path.Combine("src", "PdfPecker", "Html", "HtmlEntities.g.cs");

var full = new SortedDictionary<string, int[]>(StringComparer.Ordinal);
var legacy = new SortedSet<string>(StringComparer.Ordinal);
int total = 0;
foreach (var entry in json.RootElement.EnumerateObject())
{
    total++;
    string key = entry.Name;
    if (key[0] != '&') throw new InvalidDataException("Unexpected key " + key);
    int[] cps = entry.Value.GetProperty("codepoints").EnumerateArray().Select(e => e.GetInt32()).ToArray();
    if (key.EndsWith(';')) full.Add(key[1..^1], cps);
    else legacy.Add(key[1..]);
}
if (total != ExpectedNames || legacy.Count != ExpectedLegacy)
    throw new InvalidDataException($"{total} names and {legacy.Count} legacy names; expected {ExpectedNames} and {ExpectedLegacy}.");
// Every legacy name also exists with its semicolon and decodes to the same text, so the decoder keeps one table.
foreach (var name in legacy)
    if (!full.TryGetValue(name, out var cps) || cps.Length != 1)
        throw new InvalidDataException("The legacy name " + name + " has no single-character form with ';'.");

var o = new StringBuilder();
o.Append("""
    // <auto-generated>
    // Generated by tools/HtmlEntities from the WHATWG HTML Standard's entities.json. Do not edit by hand.
    // </auto-generated>
    namespace PdfPecker.Html;

    internal static partial class HtmlEntities
    {
        // Every name (without '&' and ';') with its code points in hex, separated by spaces.
        private const string NamedTable =

    """);
AppendWrapped(full.Select(p => p.Key + "=" + string.Join(",", p.Value.Select(cp => cp.ToString("X")))));
o.Append("""

        // The legacy names, which also decode without a ';' (HTML 13.2.5.73).
        private const string LegacyNames =

    """);
AppendWrapped(legacy);
o.Append("}\n");
File.WriteAllText(output, o.ToString());
Console.WriteLine($"{output}: {full.Count} names, {legacy.Count} legacy names");
return 0;

// Writes the items as concatenated string literals of about 110 characters a line, ending with ';'.
void AppendWrapped(IEnumerable<string> items)
{
    var line = new StringBuilder();
    var lines = new List<string>();
    foreach (var item in items)
    {
        if (line.Length > 0 && line.Length + item.Length + 1 > 104)
        {
            lines.Add(line.ToString());
            line.Clear();
        }
        if (line.Length > 0) line.Append(' ');
        line.Append(item);
    }
    lines.Add(line.ToString());
    for (int i = 0; i < lines.Count; i++)
    {
        bool last = i == lines.Count - 1;
        o.Append("        \"").Append(lines[i]).Append(last ? "\";\n" : " \" +\n");
    }
}
