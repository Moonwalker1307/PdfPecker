# Regenerates tests/PdfPecker.Tests/Fixtures/shaping/harfbuzz.txt: HarfBuzz's glyphs for the texts in corpus.txt,
# which IndicShapingTests compares PdfPecker's Indic, Thai and Lao shaping with.
#
# Usage (from the repository root): pip install uharfbuzz fonttools brotli, then
#   python3 tools/ShapingReference/generate.py
#
# The fonts are the WOFF2 subsets in tests/PdfPecker.Tests/Fixtures/fonts; HarfBuzz is given the same font as TrueType.
# Each output line is the font, the text (as in the corpus) and the glyphs: glyph id, then the advance and the x and
# y offsets in font units.
import io, os, re, sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
fonts = os.path.join(root, "tests", "PdfPecker.Tests", "Fixtures", "fonts")
out_path = os.path.join(root, "tests", "PdfPecker.Tests", "Fixtures", "shaping", "harfbuzz.txt")

def text_of(field):
    m = re.fullmatch(r"<(.*)>", field)
    return "".join(chr(int(u[2:], 16)) for u in m.group(1).split()) if m else field

cache = {}
def font_of(name):
    if name not in cache:
        tt = TTFont(os.path.join(fonts, name + ".woff2"))
        tt.flavor = None
        data = io.BytesIO()
        tt.save(data)
        cache[name] = hb.Font(hb.Face(data.getvalue()))
    return cache[name]

lines = [f"# HarfBuzz {hb.version_string()} (uharfbuzz), generated by tools/ShapingReference/generate.py; do not edit by hand."]
for line in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "corpus.txt"), encoding="utf-8"):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    name, field = line.split("\t")
    buf = hb.Buffer()
    buf.add_str(text_of(field))
    buf.guess_segment_properties()
    buf.flags = hb.BufferFlags.REMOVE_DEFAULT_IGNORABLES
    hb.shape(font_of(name), buf)
    glyphs = " ".join(f"{i.codepoint}@{p.x_advance},{p.x_offset},{p.y_offset}" for i, p in zip(buf.glyph_infos, buf.glyph_positions))
    lines.append(f"{name}\t{field}\t{glyphs}")
os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{out_path}: {len(lines) - 1} texts")
