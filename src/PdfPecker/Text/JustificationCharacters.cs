    /// <summary>Whether Chrome counts a character as a CJK ideograph or symbol, which text is justified around.</summary>
    public static bool IsCjkIdeographOrSymbol(int cp)
    {
        if (cp < 0x2C7) return false;
        var ranges = CjkRanges;
        int lo = 0, hi = ranges.Length / 2 - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            if (cp < ranges[mid * 2]) hi = mid - 1;
            else if (cp > ranges[mid * 2 + 1]) lo = mid + 1;
            else return true;
        }
        return false;
    }

    /// <summary>
    /// Whether a character belongs to a script whose letters join (Arabic, Syriac, Mandaic, N'Ko, Hanifi Rohingya,
    /// Mongolian and Phags-pa): inter-character justification never puts space between its letters.
    /// </summary>
    public static bool IsCursive(int cp) => cp is (>= 0x0600 and <= 0x077F) or (>= 0x07C0 and <= 0x07FF) or (>= 0x0840 and <= 0x085F)
        or (>= 0x0860 and <= 0x08FF) or (>= 0x1800 and <= 0x18AF) or (>= 0xA840 and <= 0xA87F) or (>= 0xFB50 and <= 0xFDFF)
        or (>= 0xFE70 and <= 0xFEFF) or (>= 0x10D00 and <= 0x10D3F) or (>= 0x11660 and <= 0x1167F) or (>= 0x1EC70 and <= 0x1ECBF);

    /// <summary>Whether a character is default ignorable (format controls, variation selectors, ...): it is never justified.</summary>
    public static bool IsDefaultIgnorable(int cp) => cp is 0x034F or 0x115F or 0x1160 or 0x17B4 or 0x17B5 or 0x3164 or 0xFFA0
        or (>= 0x180B and <= 0x180F) or (>= 0xFE00 and <= 0xFE0F) or (>= 0xE0000 and <= 0xE0FFF)
        || CharUnicodeInfo.GetUnicodeCategory(cp) == UnicodeCategory.Format;

    /// <summary>
    /// Whether a character continues the grapheme cluster before it (a combining mark, a joiner, an emoji modifier, a
    /// variation selector or the character after a zero width joiner): justification treats a cluster as one character.
    /// </summary>
    public static bool ExtendsCluster(int cp, int previous)
    {
        if (previous == 0x200D) return true;
        if (cp is 0x200C or 0x200D or (>= 0xFE00 and <= 0xFE0F) or (>= 0x1F3FB and <= 0x1F3FF) or (>= 0xE0020 and <= 0xE007F)) return true;
        var category = CharUnicodeInfo.GetUnicodeCategory(cp);
        return category is UnicodeCategory.NonSpacingMark or UnicodeCategory.SpacingCombiningMark or UnicodeCategory.EnclosingMark;
    }

    /// <summary>Sorts first and last pairs and merges those that overlap or touch, for a binary search.</summary>
    private static int[] Merge(int[] pairs)
    {
        var ranges = new (int First, int Last)[pairs.Length / 2];
        for (int k = 0; k < ranges.Length; k++) ranges[k] = (pairs[k * 2], pairs[k * 2 + 1]);
        Array.Sort(ranges);
        var merged = new List<int>(pairs.Length);
        foreach (var (first, last) in ranges)
        {
            if (merged.Count > 0 && first <= merged[^1] + 1) merged[^1] = Math.Max(merged[^1], last);
            else { merged.Add(first); merged.Add(last); }
        }
        return merged.ToArray();
    }
