using System.Runtime.CompilerServices;
using System.Text;
using System.Text.RegularExpressions;

namespace PdfPecker.Tests;

/// <summary>
/// Converts a few of the HTML golden baselines (the PDFs PdfPecker writes) and a PDF from another tool to HTML, and
/// compares the result with checked-in HTML: the page structure, the invisible text layer, its web font and the links.
/// The page images are left out of the comparison, because their pixels can move by a rounding step between runtimes;
/// <see cref="RendererGoldenTests"/> covers the renderer that draws them.
/// </summary>
/// <remarks>
/// When a change in the output is intended, regenerate the baselines with
/// <c>PDFPECKER_UPDATE_GOLDEN=1 dotnet test --filter PdfToHtmlGoldenTests -f net10.0</c> and review them. If the input PDFs
/// were just regenerated by GoldenPdfTests, run those first. On a mismatch the new HTML is written to the test output
/// folder (golden-actual/).
/// </remarks>
public class PdfToHtmlGoldenTests
{
    private static string SourceDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

    // A small resolution keeps the baselines small; the images are replaced by a placeholder anyway.
    private static readonly PdfHtmlOptions Options = new() { Dpi = 18, ImageFormat = PdfImageFormat.Png };

    private static readonly Regex Images = new(@"data:image/[a-z]+;base64,[A-Za-z0-9+/=]*", RegexOptions.Compiled);

    // The baseline's name and the PDF, by path under the test project: internal links and footnotes, external links
    // and images, and a PDF from LibreOffice with form fields.
    public static TheoryData<string, string> Samples() => new()
    {
        { "footnotes-toc", "Golden/footnotes-toc/demo.expected.pdf" },
        { "features-images", "Golden/features/images.expected.pdf" },
        { "libreoffice", "Fixtures/third-party/libreoffice.pdf" },
    };

    [Theory]
    [MemberData(nameof(Samples))]
    public void Html_matches_the_baseline(string name, string sample)
    {
        var pdf = File.ReadAllBytes(Path.Combine(SourceDirectory(), sample));
        var actual = Images.Replace(PdfToHtml.Convert(pdf, Options), "data:image/png;base64,");
        var expectedPath = Path.Combine(SourceDirectory(), "Golden", "pdf-to-html", name + ".expected.html");

        if (Environment.GetEnvironmentVariable("PDFPECKER_UPDATE_GOLDEN") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(expectedPath)!);
            File.WriteAllText(expectedPath, actual, new UTF8Encoding(false));
            return;
        }
        Assert.True(File.Exists(expectedPath), $"No baseline for {sample}. Create it with PDFPECKER_UPDATE_GOLDEN=1.");

        var expected = File.ReadAllText(expectedPath).ReplaceLineEndings("\n");
        if (expected == actual) return;
        int at = 0;
        while (at < expected.Length && at < actual.Length && expected[at] == actual[at]) at++;
        var outDir = Path.Combine(AppContext.BaseDirectory, "golden-actual");
        Directory.CreateDirectory(outDir);
        var outPath = Path.Combine(outDir, name + ".html");
        File.WriteAllText(outPath, actual, new UTF8Encoding(false));
        Assert.Fail($"{sample} differs from its baseline at character {at}: expected \"{Excerpt(expected, at)}\", got \"{Excerpt(actual, at)}\"\nNew output: {outPath}");
    }

    private static string Excerpt(string s, int at) => s.Substring(Math.Max(0, at - 40), Math.Min(s.Length, at + 40) - Math.Max(0, at - 40));
}
