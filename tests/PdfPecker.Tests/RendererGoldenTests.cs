using System.Buffers.Binary;
using System.IO.Compression;
using System.Runtime.CompilerServices;
using System.Text;

namespace PdfPecker.Tests;

/// <summary>
/// Renders the first page of a few of the HTML golden baselines (the PDFs PdfPecker writes) at a low, fixed resolution
/// and compares the result with checked-in PNGs, so an unintended change in the PDF-to-image renderer shows up. The
/// comparison tolerates small per-channel differences and a few differing pixels, because anti-aliased edges can move by
/// a rounding step between runtimes.
/// </summary>
/// <remarks>
/// When a change in the renderer is intended, regenerate the PNGs with
/// <c>PDFPECKER_UPDATE_GOLDEN=1 dotnet test --filter RendererGoldenTests -f net10.0</c> and review them. If the input PDFs
/// were just regenerated by GoldenPdfTests, run the PDF baselines first and the PNG baselines in a second run. On a mismatch
/// the new rendering is written to the test output folder (golden-actual/).
/// </remarks>
public class RendererGoldenTests
{
    private const float Dpi = 36;
    private const int ChannelTolerance = 24;
    private const double MaxDifferingFraction = 0.005;

    private static readonly string Root = Path.Combine(SourceDirectory(), "Golden");

    private static string SourceDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

    public static TheoryData<string> Samples() => new()
    {
        "css3/demo",
        "svg-effects/demo",
        "transparency/demo",
        "image-formats/demo",
        "translucent-effects/demo",
        "hyphenation/demo",
    };

    [Theory]
    [MemberData(nameof(Samples))]
    public void First_page_matches_the_baseline_png(string sample)
    {
        var pdf = File.ReadAllBytes(Path.Combine(Root, sample + ".expected.pdf"));
        var options = new ImageOptions { Dpi = Dpi, PngCompression = CompressionLevel.SmallestSize };
        var actual = PdfRenderer.Open(pdf).RenderPage(0, options);
        var pngPath = Path.Combine(Root, "render", sample.Replace('/', '-') + ".png");

        if (Environment.GetEnvironmentVariable("PDFPECKER_UPDATE_GOLDEN") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(pngPath)!);
            File.WriteAllBytes(pngPath, actual.ToPng());
            return;
        }
        Assert.True(File.Exists(pngPath), $"No baseline for {sample}. Create it with PDFPECKER_UPDATE_GOLDEN=1.");

        var (width, height, expected) = DecodePng(File.ReadAllBytes(pngPath));
        string? failure = null;
        if (width != actual.Width || height != actual.Height)
            failure = $"size {actual.Width}x{actual.Height} instead of {width}x{height}";
        else
        {
            var rgba = actual.Rgba;
            int differing = 0, worst = 0;
            for (int i = 0; i < rgba.Length; i += 4)
            {
                int d = Math.Max(Math.Max(Math.Abs(rgba[i] - expected[i]), Math.Abs(rgba[i + 1] - expected[i + 1])), Math.Abs(rgba[i + 2] - expected[i + 2]));
                if (d > ChannelTolerance) differing++;
                worst = Math.Max(worst, d);
            }
            int allowed = (int)(width * height * MaxDifferingFraction);
            if (differing > allowed) failure = $"{differing} pixels differ by more than {ChannelTolerance} (allowed {allowed}, worst channel difference {worst})";
        }
        if (failure == null) return;
        var outDir = Path.Combine(AppContext.BaseDirectory, "golden-actual");
        Directory.CreateDirectory(outDir);
        var outPath = Path.Combine(outDir, "render-" + sample.Replace('/', '-') + ".png");
        File.WriteAllBytes(outPath, actual.ToPng());
        Assert.Fail($"{sample} renders differently from its baseline: {failure}\nNew rendering: {outPath}");
    }

    /// <summary>Decodes the 8-bit RGB or RGBA PNGs the renderer writes into straight RGBA.</summary>
    private static (int Width, int Height, byte[] Rgba) DecodePng(byte[] png)
    {
        Assert.Equal(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A }, png[..8]);
        int pos = 8, width = 0, height = 0, colorType = 0;
        var idat = new MemoryStream();
        while (pos < png.Length)
        {
            int len = BinaryPrimitives.ReadInt32BigEndian(png.AsSpan(pos));
            string type = Encoding.ASCII.GetString(png, pos + 4, 4);
            var data = png.AsSpan(pos + 8, len);
            if (type == "IHDR")
            {
                width = BinaryPrimitives.ReadInt32BigEndian(data);
                height = BinaryPrimitives.ReadInt32BigEndian(data[4..]);
                colorType = data[9];
            }
            else if (type == "IDAT") idat.Write(data);
            pos += 12 + len;
        }
        idat.Position = 0;
        var raw = new MemoryStream();
        using (var z = new ZLibStream(idat, CompressionMode.Decompress)) z.CopyTo(raw);
        var bytes = raw.ToArray();
        int bpp = colorType == 6 ? 4 : 3, stride = width * bpp;
        var prev = new byte[stride];
        var rgba = new byte[width * height * 4];
        for (int y = 0; y < height; y++)
        {
            int filter = bytes[y * (stride + 1)];
            var cur = bytes.AsSpan(y * (stride + 1) + 1, stride).ToArray();
            for (int i = 0; i < stride; i++)
            {
                int a = i >= bpp ? cur[i - bpp] : 0, b = prev[i], c = i >= bpp ? prev[i - bpp] : 0;
                int predicted = filter switch
                {
                    1 => a,
                    2 => b,
                    3 => (a + b) / 2,
                    4 => Paeth(a, b, c),
                    _ => 0,
                };
                cur[i] = (byte)(cur[i] + predicted);
            }
            for (int x = 0; x < width; x++)
            {
                int o = (y * width + x) * 4;
                rgba[o] = cur[x * bpp];
                rgba[o + 1] = cur[x * bpp + 1];
                rgba[o + 2] = cur[x * bpp + 2];
                rgba[o + 3] = bpp == 4 ? cur[x * bpp + 3] : (byte)255;
            }
            prev = cur;
        }
        return (width, height, rgba);
    }

    private static int Paeth(int a, int b, int c)
    {
        int p = a + b - c, pa = Math.Abs(p - a), pb = Math.Abs(p - b), pc = Math.Abs(p - c);
        return pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
    }
}
